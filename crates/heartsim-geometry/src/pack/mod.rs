//! Anatomy pack: the on-disk bundle the engines and renderer consume (`docs/ARCHITECTURE.md` §7).
//!
//! ```text
//! <pack>/
//!   manifest.ron       format version, provenance, licence, frame, file sizes + CRC-32s
//!   LICENSE            licence and attribution of the geometry
//!   mesh_<name>.glb    render meshes (glTF binary; POSITION, NORMAL, u32 indices)
//!   torso.glb          body surface
//!   cells.bin          positions, fibres, region codes, transmural depth
//!   neighbours.bin     8 nearest neighbours per cell with distance and fibre alignment
//!   segments.bin       AHA 17-segment index per cell (coronary territories derive from it)
//!   hoods/<name>.bin   8 nearest cells + inverse-distance weights per vertex of each myocardial mesh
//!   landmarks.ron      named cells and named cell sets (PMJ seeds per fascicle)
//!   electrodes.ron     electrode sites in the heart frame
//! ```
//!
//! Loading verifies the format version, every file's size and CRC-32, and the cross-file counts, so
//! a pack that loads is internally consistent.

mod binary;
mod glb;

pub use binary::{region_from_u8, region_to_u8};
pub use glb::{read_glb, write_glb};

use crate::cloud::CellCloud;
use crate::electrodes::ElectrodeSet;
use crate::hood::{Hood, compute_hoods};
use crate::mesh::TriMesh;
use crate::procedural::{MeshKind, NamedMesh, Resolution, idealised_heart, procedural_torso};
use crate::territory::Territory;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

/// Bump when the set of files or their meaning changes; binary record versions live in `binary`.
pub const PACK_FORMAT_VERSION: u32 = 1;
/// Description of the coordinate frame written into every manifest.
pub const HEART_FRAME: &str =
    "millimetres; origin = ventricular centroid; +x = patient's left, +y = cranial, +z = anterior";

#[derive(Debug, thiserror::Error)]
pub enum PackError {
    #[error("{path}: {source}")]
    Io {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("manifest parse error: {0}")]
    Manifest(#[from] ron::error::SpannedError),
    #[error("RON serialisation error: {0}")]
    Ron(#[from] ron::Error),
    #[error("pack format version {found} is not supported (this build reads {PACK_FORMAT_VERSION})")]
    Version { found: u32 },
    #[error("{file}: checksum mismatch (expected {expected:08x}, found {found:08x})")]
    Checksum { file: String, expected: u32, found: u32 },
    #[error("{file}: size mismatch (manifest says {expected} bytes, file has {found})")]
    Size { file: String, expected: u64, found: u64 },
    #[error("{0}")]
    Format(String),
}

/// Size and CRC-32 of one pack file.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct FileEntry {
    pub bytes: u64,
    pub crc32: u32,
}

/// One render mesh of the pack.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MeshEntry {
    pub name: String,
    pub file: String,
    pub kind: MeshKind,
    pub vertices: u32,
    pub triangles: u32,
}

/// `manifest.ron`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PackManifest {
    pub format_version: u32,
    pub name: String,
    /// Where the geometry came from (dataset + record, or the procedural generator and its version).
    pub source: String,
    pub licence: String,
    pub frame: String,
    pub cell_spacing_mm: f32,
    pub cell_count: u32,
    pub meshes: Vec<MeshEntry>,
    /// Every file except the manifest itself, keyed by path relative to the pack directory.
    pub files: BTreeMap<String, FileEntry>,
}

/// `landmarks.ron`: named cells and named cell sets.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Landmarks {
    /// e.g. `sa_node`, `av_node`, `his`, `rbb`, `lbb`, `laf`, `lpf`, `rv_apex`, `lv_lateral`, …
    pub points: BTreeMap<String, u32>,
    /// Purkinje–myocardial junction seeds per fascicle (`rbb`, `laf`, `lpf`) and other cell sets.
    pub sets: BTreeMap<String, Vec<u32>>,
}

/// A loaded (or freshly generated) anatomy pack.
#[derive(Debug, Clone)]
pub struct AnatomyPack {
    pub manifest: PackManifest,
    pub meshes: Vec<NamedMesh>,
    /// Cell cloud with its neighbour graph; `cells.landmarks` mirrors `landmarks.points`.
    pub cells: CellCloud,
    /// Hoods per myocardial mesh name.
    pub hoods: BTreeMap<String, Vec<Hood>>,
    pub landmarks: Landmarks,
    pub electrodes: ElectrodeSet,
    pub torso: TriMesh,
    /// AHA 17-segment index per cell (0 = none).
    pub aha_segments: Vec<u8>,
}

/// Procedural pack licence text (the pack is heartsim's own work).
pub const PROCEDURAL_LICENSE: &str = "heartsim procedural anatomy pack\n\n\
Geometry generated by heartsim-geometry::procedural::idealised_heart and procedural_torso from\n\
published population-average dimensions (Lang et al. 2015 echocardiographic normal ranges; Kligfield\n\
et al. 2007 electrode placement; Bayer 2012 / Streeter 1969 fibre rule; Cerqueira 2002 AHA segments).\n\
No third-party mesh, texture or data file was used.\n\n\
Licensed under MIT OR Apache-2.0, the same terms as the heartsim source code.\n";

impl AnatomyPack {
    /// The procedural idealised heart + torso as a complete pack (no files touched).
    #[must_use]
    pub fn procedural(resolution: Resolution) -> Self {
        let heart = idealised_heart(resolution);
        let torso = procedural_torso(resolution.mesh_voxel_mm.max(2.0) * 5.0);
        let hoods = heart
            .meshes
            .iter()
            .filter(|m| m.conducting())
            .map(|m| (m.name.clone(), compute_hoods(&m.mesh, &heart.cells)))
            .collect();
        let landmarks = Landmarks {
            points: heart.cells.landmarks.clone(),
            sets: heart.pmj_seeds.clone(),
        };
        let manifest = PackManifest {
            format_version: PACK_FORMAT_VERSION,
            name: "default".to_string(),
            source: format!(
                "procedural idealised heart (heartsim-geometry {}, voxel {} mm, spacing {} mm)",
                env!("CARGO_PKG_VERSION"),
                resolution.mesh_voxel_mm,
                resolution.cell_spacing_mm
            ),
            licence: "MIT OR Apache-2.0".to_string(),
            frame: HEART_FRAME.to_string(),
            cell_spacing_mm: resolution.cell_spacing_mm,
            cell_count: heart.cells.len() as u32,
            meshes: heart
                .meshes
                .iter()
                .map(|m| MeshEntry {
                    name: m.name.clone(),
                    file: format!("mesh_{}.glb", m.name),
                    kind: m.kind,
                    vertices: m.mesh.vertex_count() as u32,
                    triangles: m.mesh.triangle_count() as u32,
                })
                .collect(),
            files: BTreeMap::new(),
        };
        Self {
            manifest,
            meshes: heart.meshes,
            cells: heart.cells,
            hoods,
            landmarks,
            electrodes: torso.electrodes,
            torso: torso.mesh,
            aha_segments: heart.aha_segments,
        }
    }

    /// Coronary territory of a cell.
    #[must_use]
    pub fn territory(&self, cell: u32) -> Territory {
        let i = cell as usize;
        Territory::for_cell(
            self.cells.regions[i],
            self.aha_segments.get(i).copied().unwrap_or(0),
        )
    }

    /// Render mesh by name.
    #[must_use]
    pub fn mesh(&self, name: &str) -> Option<&NamedMesh> {
        self.meshes.iter().find(|m| m.name == name)
    }

    /// Write the pack to `dir` (created if needed; existing files are overwritten). Returns the
    /// manifest with checksums filled in, which is also stored in `self.manifest`.
    pub fn save(&mut self, dir: &Path) -> Result<PackManifest, PackError> {
        std::fs::create_dir_all(dir.join("hoods")).map_err(|e| io_err(dir, e))?;
        let mut files = BTreeMap::new();
        let mut put = |rel: &str, bytes: &[u8]| -> Result<(), PackError> {
            let path = dir.join(rel);
            std::fs::write(&path, bytes).map_err(|e| io_err(&path, e))?;
            files.insert(
                rel.to_string(),
                FileEntry {
                    bytes: bytes.len() as u64,
                    crc32: crc32fast::hash(bytes),
                },
            );
            Ok(())
        };
        for m in &self.meshes {
            put(&format!("mesh_{}.glb", m.name), &write_glb(&m.mesh, &m.name))?;
        }
        put("torso.glb", &write_glb(&self.torso, "torso"))?;
        put("cells.bin", &binary::write_cells(&self.cells))?;
        put("neighbours.bin", &binary::write_neighbours(&self.cells))?;
        put("segments.bin", &binary::write_segments(&self.aha_segments))?;
        for (name, hoods) in &self.hoods {
            put(&format!("hoods/{name}.bin"), &binary::write_hoods(hoods))?;
        }
        put("landmarks.ron", to_ron(&self.landmarks)?.as_bytes())?;
        put("electrodes.ron", self.electrodes.to_ron()?.as_bytes())?;
        put("LICENSE", PROCEDURAL_LICENSE.as_bytes())?;
        self.manifest.files = files;
        self.manifest.format_version = PACK_FORMAT_VERSION;
        self.manifest.cell_count = self.cells.len() as u32;
        self.manifest.meshes = self
            .meshes
            .iter()
            .map(|m| MeshEntry {
                name: m.name.clone(),
                file: format!("mesh_{}.glb", m.name),
                kind: m.kind,
                vertices: m.mesh.vertex_count() as u32,
                triangles: m.mesh.triangle_count() as u32,
            })
            .collect();
        let path = dir.join("manifest.ron");
        std::fs::write(&path, to_ron(&self.manifest)?).map_err(|e| io_err(&path, e))?;
        Ok(self.manifest.clone())
    }

    /// Load and verify a pack directory.
    pub fn load(dir: &Path) -> Result<Self, PackError> {
        Self::load_with(|rel| {
            let path = dir.join(rel);
            std::fs::read(&path).map_err(|e| io_err(&path, e))
        })
    }

    /// Load and verify a pack whose files come from `read_file` (a path relative to the pack root,
    /// `manifest.ron` first), e.g. from memory after a download where there is no directory to
    /// read. Every file is still checked against the manifest's size and CRC-32, so a truncated
    /// download is reported, never half-loaded.
    pub fn load_with(
        mut read_file: impl FnMut(&str) -> Result<Vec<u8>, PackError>,
    ) -> Result<Self, PackError> {
        let text = String::from_utf8_lossy(&read_file("manifest.ron")?).into_owned();
        let manifest: PackManifest = ron::from_str(&text)?;
        if manifest.format_version != PACK_FORMAT_VERSION {
            return Err(PackError::Version {
                found: manifest.format_version,
            });
        }
        let mut read = |rel: &str| -> Result<Vec<u8>, PackError> {
            let entry = manifest
                .files
                .get(rel)
                .ok_or_else(|| PackError::Format(format!("{rel}: not listed in manifest")))?;
            let bytes = read_file(rel)?;
            if bytes.len() as u64 != entry.bytes {
                return Err(PackError::Size {
                    file: rel.to_string(),
                    expected: entry.bytes,
                    found: bytes.len() as u64,
                });
            }
            let found = crc32fast::hash(&bytes);
            if found != entry.crc32 {
                return Err(PackError::Checksum {
                    file: rel.to_string(),
                    expected: entry.crc32,
                    found,
                });
            }
            Ok(bytes)
        };

        let mut meshes = Vec::with_capacity(manifest.meshes.len());
        for entry in &manifest.meshes {
            let mesh = read_glb(&read(&entry.file)?)?;
            if mesh.vertex_count() != entry.vertices as usize
                || mesh.triangle_count() != entry.triangles as usize
            {
                return Err(PackError::Format(format!(
                    "{}: {} vertices / {} triangles, manifest says {} / {}",
                    entry.file,
                    mesh.vertex_count(),
                    mesh.triangle_count(),
                    entry.vertices,
                    entry.triangles
                )));
            }
            meshes.push(NamedMesh {
                name: entry.name.clone(),
                kind: entry.kind,
                mesh,
            });
        }
        let torso = read_glb(&read("torso.glb")?)?;

        let (positions, fibres, regions, depth) = binary::read_cells(&read("cells.bin")?)?;
        let n = positions.len();
        if n != manifest.cell_count as usize {
            return Err(PackError::Format(format!(
                "cells.bin: {n} cells, manifest says {}",
                manifest.cell_count
            )));
        }
        let neighbours = binary::read_neighbours(&read("neighbours.bin")?, n)?;
        if neighbours
            .iter()
            .flatten()
            .any(|e| e.index != u32::MAX && e.index as usize >= n)
        {
            return Err(PackError::Format("neighbours.bin: index out of range".into()));
        }
        let aha_segments = binary::read_segments(&read("segments.bin")?, n)?;

        let landmarks: Landmarks = ron::from_str(&String::from_utf8_lossy(&read("landmarks.ron")?))?;
        if landmarks
            .points
            .values()
            .chain(landmarks.sets.values().flatten())
            .any(|i| *i as usize >= n)
        {
            return Err(PackError::Format("landmarks.ron: cell index out of range".into()));
        }
        let electrodes = ElectrodeSet::from_ron(&String::from_utf8_lossy(&read("electrodes.ron")?))?;

        let mut hoods = BTreeMap::new();
        for m in meshes.iter().filter(|m| m.conducting()) {
            let h = binary::read_hoods(&read(&format!("hoods/{}.bin", m.name))?, m.mesh.vertex_count())?;
            if h.iter().flat_map(|h| h.cells).any(|c| c as usize >= n) {
                return Err(PackError::Format(format!(
                    "hoods/{}.bin: cell index out of range",
                    m.name
                )));
            }
            hoods.insert(m.name.clone(), h);
        }

        let cells = CellCloud {
            positions,
            fibres,
            regions,
            depth,
            neighbours,
            landmarks: landmarks.points.clone(),
        };
        Ok(Self {
            manifest,
            meshes,
            cells,
            hoods,
            landmarks,
            electrodes,
            torso,
            aha_segments,
        })
    }
}

fn io_err(path: &Path, source: std::io::Error) -> PackError {
    PackError::Io {
        path: path.to_path_buf(),
        source,
    }
}

fn to_ron<T: Serialize>(v: &T) -> Result<String, PackError> {
    Ok(ron::ser::to_string_pretty(
        v,
        ron::ser::PrettyConfig::default()
            .struct_names(true)
            .compact_arrays(true),
    )?)
}
